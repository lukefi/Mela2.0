from typing import Any

import numpy as np

from lukefi.metsi.core.exceptions import MetsiException
from lukefi.metsi.data.enums.internal import CuttingMethod, Storey, TreeManagementCategory
from lukefi.metsi.data.model import ForestStand
from lukefi.metsi.data.vector_model import ReferenceTrees
from lukefi.metsi.domain.collected_data import RemovedTrees
from lukefi.metsi.domain.natural_processes.motti_util import (
    reconcile_reference_trees_from_motti,
    update_motti_state_after_cutting)
from lukefi.metsi.forestry.aggregates_internal import calc_tree_basal_areas
from lukefi.metsi.forestry.naturalprocess.motti_dll_wrapper import Motti4DLL
from lukefi.metsi.core.collected_data import CollectedData, OpTuple
from lukefi.metsi.core.treatment import Treatment
from lukefi.metsi.core.utils.select_units import Mode, SelectionSet, SelectionTarget, select_units
from lukefi.metsi.forestry.storey import update_storeys


def seedtree_cutting_fn(stand: ForestStand,
                        /,
                        seed_tree_class: int = 3,
                        tree_selection: dict[str, Any] | None = None,
                        cutting_method: CuttingMethod | None = None,
                        mode: Mode = Mode.ODDS_UNITS,
                        select_from_all: bool = False
                        ) -> OpTuple[ForestStand]:
    """
    Seed-tree cutting treatment.

    First performs the normal cutting treatment, including ReferenceTrees -> YP
    stem-count reduction when Motti is used. Then marks all remaining YP trees as tree class 3 and
    calls Motti4AfterSeedtreeCutting so Motti can create natural regeneration
    into the sapling vector.
    """
    trees = stand.reference_trees

    if stand.reference_trees.size == 0:
        return stand, []

    if tree_selection is None or "target" not in tree_selection or "sets" not in tree_selection:
        raise MetsiException("Missing 'tree_selection' with 'target' and 'sets'.")

    if cutting_method is None:
        raise MetsiException("Required parameter 'cutting_method' is missing!")

    target: SelectionTarget = tree_selection["target"]

    # Sets
    sets: list[SelectionSet[ForestStand, ReferenceTrees]] = tree_selection["sets"]
    if len(sets) == 0:
        raise MetsiException("tree_selection.sets must be a non-empty list.")

    # Run selection
    removed_f = select_units(
        context=stand,
        data=trees,
        target_decl=target,
        sets=sets,
        freq_var="stems_per_ha",
        select_from_all=select_from_all,
        mode=mode,
    )

    # Apply removals
    if not trees.stems_per_ha.flags.writeable:
        trees.stems_per_ha = trees.stems_per_ha.copy()
        trees.stems_per_ha.flags.writeable = True
    trees.stems_per_ha -= removed_f

    # Collected data: Removed trees
    removed_mask = removed_f > 0.0
    collected: list[CollectedData] = []
    if np.any(removed_mask):
        removed_view = trees[removed_mask]
        # record the removed amounts as stems_per_ha in the collected view
        removed_view.stems_per_ha = removed_f[removed_mask].copy()
        rt = RemovedTrees()
        rt.removed_trees = removed_view
        collected = [rt]

    # If Motti is in use, update removed trees to yp vector
    if stand.motti_state is not None:
        update_motti_state_after_cutting(stand, removed_f)

    stand.cutting_year = stand.year
    stand.method_of_last_cutting = cutting_method

    # Set all remaining trees to OVER storey and designate as seeding trees
    trees.storey = np.full(len(trees), Storey.OVER)
    trees.management_category = np.full(len(trees), TreeManagementCategory.SEEDING_TREE)

    if stand.motti_state is not None:
        _after_seedtree_cutting_in_motti(
            stand,
            seed_tree_class,
        )

    # Update storeys for new trees generated by Motti
    trees.basal_area = calc_tree_basal_areas(trees.breast_height_diameter)
    update_storeys(trees)

    return stand, collected


def _after_seedtree_cutting_in_motti(stand: ForestStand, tree_class: int) -> None:
    """Run Motti seed-tree cutting post-processing and sync Python vectors."""

    ms = stand.motti_state
    if ms is None or ms.yp is None or ms.buffers is None:
        return

    _mark_motti_yp_as_seed_trees(stand, tree_class)

    ms.ntrees = Motti4DLL.after_seedtree_cutting_with_state(
        ms.yy,
        ms.yp,
        int(ms.ntrees),
        ms.buffers,
    )

    reconcile_reference_trees_from_motti(stand)


def _mark_motti_yp_as_seed_trees(stand: ForestStand, tree_class) -> bool:
    """Mark all currently live YP trees as seed trees for Motti.

    Motti's YP vector field at documented index 38 is exposed in the
    CFFI wrapper as ``storie``. For seed-tree cutting the remaining trees
    must have puuluokka/tree class 3 before Motti4AfterSeedtreeCutting is
    called.
    """

    ms = stand.motti_state
    if ms is None or ms.yp is None:
        return False

    changed = False
    for i in range(int(ms.ntrees)):
        t = ms.yp[0][i]
        if float(t.f) <= 0.0:
            continue
        if float(t.storie) != float(tree_class):
            t.storie = float(tree_class)
            changed = True

    return changed


seedtree_cutting = Treatment(seedtree_cutting_fn, "seedtree_cutting", {"cutting"}, {RemovedTrees})
